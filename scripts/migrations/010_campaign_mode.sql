-- Purpose: режим кампании — одиночная ('solo') или сетевая ('network').
--
-- Кампания из «Создать кампанию» — solo, кампания, начатая из сетевой комнаты, — network.
-- От режима зависит, куда ведёт карточка кампании на главной: solo открывает кампанию,
-- network — стол (активную комнату кампании или новую).
--
-- Все существующие кампании становятся solo (на момент миграции комнат не было).
--
-- Скрипт можно запускать повторно.
-- =============================================================================

ALTER TABLE "Campaign" ADD COLUMN IF NOT EXISTS "mode" TEXT NOT NULL DEFAULT 'solo';
