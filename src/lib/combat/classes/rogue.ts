import { poolLeft } from "../fighter-pool";
import { PSIONIC_DICE_POOL, SOUL_TRINKETS_POOL, psionicFaces } from "../rogue-pool";

const skip = (id: string): FeatureRule => ({ id, kind: "skip" });
const passive = (id: string, extra: Partial<FeatureRule> = {}): FeatureRule => ({ id, kind: "passive", ...extra });

/** Число костей Скрытой атаки: 1к6 на 1 ур., +1к6 каждые два уровня */
export const sneakDiceCount = (level: number) => Math.ceil(Math.max(1, level) / 2);

/** Сколько кубов Могильных воплей: половина костей Скрытой атаки, с округлением вверх */
export const wailsDiceCount = (sneakDice: number) => Math.ceil(sneakDice / 2);

