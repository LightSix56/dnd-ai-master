// Плут: правила умений архетипов (заряды, цели, запасы) и постоянные поправки.
//
// Источник правил — dnd.su, редакция 2014 (PHB, Xanathar's, Tasha's), до 10 уровня включительно.
// Умения 11+ уровней описаны правилами `skip`: у героя выше 10 уровня сборка не падает, но в бою они не
// разыгрываются.
//
// Базовые умения Плута (Скрытая атака, Хитрое действие, Невероятное уклонение, Увёртливость) собирают
// library-data.ts и class-features.ts; Вор целиком идёт из SRD (class-features.ts), поэтому правил
// для него здесь нет. Что происходит при применении — в rogue-combat.ts.
//
// Названия умений в боевом интерфейсе — как на dnd.su; ключом в data/class-subclasses.json остаётся
// название из листа героя.

import { defineClass, type Calc, type FeatureRule } from "../class-defs";
